import json,pathlib
def write(path,text):
    path.write_bytes(text.encode("utf-8"))
root=pathlib.Path('.')
schemas={p.name:json.loads(p.read_text()) for p in sorted((root/'spec/schemas').glob('*.json'))}
text='// Generated from spec/schemas by scripts/sync_core_contracts.py. Do not edit.\nexport const schemas = '+json.dumps(schemas,ensure_ascii=False,separators=(',',':'))+';\n'
write((root/'packages/javascript/src/contracts.js'),text)
write((root/'packages/typescript/src/contracts.ts'),'// @ts-nocheck\n'+text)
write((root/'bindings/python/foreverworks/contracts.json'),json.dumps(schemas,ensure_ascii=False,indent=2)+'\n')

s=(root/'bindings/python/foreverworks/contracts.json').read_bytes()+b'\0'
write((root/'bindings/c/src/contracts.inc'),'/* Generated by scripts/sync_core_contracts.py. */\nstatic const unsigned char contract_json[]={'+',\n'.join(','.join(map(str,s[i:i+24])) for i in range(0,len(s),24))+'};\n')

# Shared algorithms: these are deliberately not independent semantic proofs.
for name in ['canonical','structure','json-input','lossless-json']:
 write((root/f'packages/typescript/src/{name}.ts'),'// @ts-nocheck\n'+(root/f'packages/javascript/src/{name}.js').read_text())
