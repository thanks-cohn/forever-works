import json,pathlib
root=pathlib.Path('.')
schemas={p.name:json.loads(p.read_text()) for p in sorted((root/'spec/schemas').glob('*.json'))}
text='// Generated from spec/schemas by scripts/sync_core_contracts.py. Do not edit.\nexport const schemas = '+json.dumps(schemas,ensure_ascii=False,separators=(',',':'))+';\n'
(root/'packages/javascript/src/contracts.js').write_text(text)
(root/'packages/typescript/src/contracts.ts').write_text('// @ts-nocheck\n'+text)
(root/'bindings/python/foreverworks/contracts.json').write_text(json.dumps(schemas,ensure_ascii=False,indent=2)+'\n')

s=(root/'bindings/python/foreverworks/contracts.json').read_bytes()+b'\0'
(root/'bindings/c/src/contracts.inc').write_text('/* Generated by scripts/sync_core_contracts.py. */\nstatic const unsigned char contract_json[]={'+',\n'.join(','.join(map(str,s[i:i+24])) for i in range(0,len(s),24))+'};\n')

